def place(id, name, category, lat, lng, cost, duration, hours, tip, scores, area=None, count=24):
    area = area or _AREA_BY_ID.get(id)
    if area not in REGION_IDS:
        raise ValueError(f"Unknown Kochi area for {id}: {area}")
    return dict(
        id=id,
        name=name,
        category=category,
        area=area,
        area_name=REGION_NAMES[area],
        lat=lat,
        lng=lng,
        cost=cost,
        price_tier="premium" if cost >= 2500 else "standard",
        duration=duration,
        opens=hours[0],
        closes=hours[1],
        tip=tip,
        slh=dict(
            safety=scores[0],
            legitimacy=scores[1],
            hygiene=scores[2],
            reviews=count,
            reviewed_at="2026-09-01",
            source="Illustrative seed data",
        ),
        demo=True,
    )


