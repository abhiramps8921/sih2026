def slh_score(slh):
    values = [slh.get(k) for k in ("safety", "legitimacy", "hygiene")]
    if any(
        not isinstance(v, (float, int)) or isinstance(v, bool) or not 1 <= v <= 5 for v in values
    ):
        return None
    return round(sum(values) / 15 * 100)
